const LETTER_ORDER_119 = [
  'א', 'ב', 'ג', 'ד', 'ה', 'ו', 'ז', 'ח', 'ט', 'י', 'כ', 'ל', 'מ', 'נ', 'ס', 'ע', 'פ', 'צ', 'ק', 'ר', 'ש', 'ת'
];

function normalizePsalm119Letter(letter) {
  return String(letter || '')
    .replace(/ך/g, 'כ')
    .replace(/ם/g, 'מ')
    .replace(/ן/g, 'נ')
    .replace(/ף/g, 'פ')
    .replace(/ץ/g, 'צ');
}

function chapterText(chapterNumber) {
  const chapter = tehilimData?.[chapterNumber];
  const verses = chapter?.verses || [];
  if (!Array.isArray(verses) || verses.length === 0) {
    return `פרק ${chapterNumber} לא זמין במלואו כרגע.`;
  }
  return verses.join('\n');
}

function buildPsalm119LetterFull(letter) {
  const normalized = normalizePsalm119Letter(letter);
  const idx = LETTER_ORDER_119.indexOf(normalized);
  const all = Array.isArray(tehilimData?.[119]?.verses) ? tehilimData[119].verses : [];
  if (idx === -1 || all.length < 176) {
    return `${letter}: לא נמצא טקסט מלא עבור אות זו.`;
  }
  const start = idx * 8;
  return `${letter}:\n${all.slice(start, start + 8).join('\n')}`;
}

function buildLettersBlock(letters, title = 'אותיות:') {
  if (!letters.length) return `${title}\nלא הוזן שם.`;
  return [title, letters.join(' '), ...letters.map((l) => buildPsalm119LetterFull(l))].join('\n\n');
}


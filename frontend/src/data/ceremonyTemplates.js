function normalizeDeceasedName(rawName) {
  const n = String(rawName || '').trim();
  if (!n) return '';
  return n
    .replace(/\s+/g, ' ')
    .replace(/(בן|בת)\s+([א-ת"׳״]+)\s+\1\s+\2/g, '$1 $2')
    .trim();
}

function extractHebrewLetters(rawName) {
  return String(rawName || '')
    .replace(/[^א-ת]/g, '')
    .split('')
    .filter(Boolean);
}

